# Builds results/tables.md (wide tables per part) + results/versions.md from the CSVs
suppressPackageStartupMessages({library(dplyr); library(tidyr); library(readr)})
short <- \(x, n = 70) ifelse(is.na(x), "", ifelse(nchar(x) > n, paste0(substr(x, 1, n - 1), "…"), x)) |> gsub("\\|", "\\\\|", x = _)
cell <- \(outcome, failed_at, value, warnings)
  ifelse(outcome == "error", paste0("❌ ", ifelse(is.na(failed_at), "", paste0("[", failed_at, "] ")), sub("^ERROR: ", "", value)),
         ifelse(outcome == "warning", paste0("⚠️ ", value, " (warn: ", warnings, ")"), paste0("✅ ", value))) |> short()
md_table <- \(df) c(paste0("| ", paste(names(df), collapse = " | "), " |"),
                    paste0("|", strrep("---|", ncol(df))),
                    apply(df, 1, \(r) paste0("| ", paste(r, collapse = " | "), " |")))

parts <- c("01-nse" = "Part 1 — NSE / data masking", "02-box" = "Part 2 — box", "03-callr-crew" = "Part 3 — callr / crew",
           "06-escape-hatches" = "Part 6 — dbplyr options and escape hatches", "07-box-base" = "Part 7 — box::use(base)")
# build/render/execute are dbplyr stages; in the callr/crew and box-base parts a failure is just "the call failed"
no_stage <- c("03-callr-crew", "07-box-base")
tables <- purrr::imap(parts, \(title, f) {
  r <- read_csv(file.path("results", paste0(f, ".csv")), show_col_types = FALSE) |>
    mutate(failed_at = if (f %in% no_stage) NA_character_ else failed_at,
           out = cell(outcome, failed_at, value, warnings), case = short(case, 60)) |>
    select(case, backend, out) |> distinct(case, backend, .keep_all = TRUE)
  w <- if (all(r$backend == "-" | r$backend %in% c("tibble", "duckdb", "sqlite")) && !all(r$backend == "-"))
    pivot_wider(r, names_from = backend, values_from = out) |> rename(`case` = case) else select(r, case, backend, result = out)
  c(paste0("## ", title), "", md_table(w), "")
}) |> unlist()
writeLines(c("# Result tables (auto-generated by build-report.R)", "",
             "`[build]` = failed when the verb (`mutate()`, `filter()`) was called; `[render]` = failed when the SQL text was made (`show_query()`, `collect()`); `[execute]` = failed in the database (`collect()`). Backends: `tibble` = in-memory dplyr; `duckdb` / `sqlite` = dbplyr lazy tables. Parts 4 (targets) and 5 (SQL Server / Oracle) have their own tables in `docs/` and their CSVs.", "", tables),
           "results/tables.md")

pk <- c("R", "dplyr", "dbplyr", "DBI", "duckdb", "RSQLite", "box", "callr", "crew", "mirai", "tidyselect", "rlang", "stringr", "lubridate", "testthat", "withr", "targets", "tarchetypes", "igraph", "lintr")
cran <- tryCatch(available.packages(repos = getOption("repos")[1]), error = \(e) NULL)
ver <- tibble(package = pk) |>
  mutate(used = ifelse(package == "R", paste(R.version$major, R.version$minor, sep = "."), vapply(package, \(p) if (p == "R") paste(R.version$major, R.version$minor, sep = ".") else as.character(packageVersion(p)), "")),
         latest = ifelse(package == "R", NA, if (is.null(cran)) NA_character_ else unname(cran[match(package, rownames(cran)), "Version"])),
         newer_available = ifelse(is.na(latest), "?", ifelse(package_version(used) < package_version(latest), "yes", "no")))
writeLines(c("| package | used | latest on CRAN mirror | newer? |", "|---|---|---|---|",
             apply(ver, 1, \(r) paste0("| ", paste(replace(r, is.na(r), "-"), collapse = " | "), " |"))), "results/versions.md")
cat(readLines("results/versions.md"), sep = "\n")
